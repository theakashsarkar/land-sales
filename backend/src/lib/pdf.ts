import PDFDocument from "pdfkit";
import type { Prisma } from "@prisma/client";

const PAGE_WIDTH = 595; // A4 72dpi
const MARGIN = 40;
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2;

export function formatMoneyForDoc(value: Prisma.Decimal.Value): string {
  const num = typeof value === "string" || typeof value === "number" ? String(value) : String(value);
  const d = Number(num);
  if (!Number.isFinite(d)) return num;
  return d.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

interface DocMeta {
  title: string;
  subtitle?: string;
  orgName: string;
  orgLines?: string[];
}

interface DocTable {
  columns: { header: string; width: number; align?: "left" | "right" }[];
  rows: (string | number)[][];
  footer?: { label: string; value: string }[];
}

/**
 * Render a simple business document PDF (invoice/receipt/report) and
 * resolve with the finished Buffer. Uses only PDFKit's standard fonts so
 * no font files need to ship with the deployment.
 */
export function buildDocumentPdf(
  meta: DocMeta,
  blocks: Array<
    | { kind: "keyValue"; rows: [string, string][] }
    | { kind: "table"; table: DocTable }
    | { kind: "text"; text: string }
    | { kind: "spacer"; height?: number }
  >,
): Promise<Buffer> {
  const doc = new PDFDocument({ size: "A4", margin: MARGIN });
  const chunks: Buffer[] = [];
  doc.on("data", (c: Buffer) => chunks.push(c));
  const done = new Promise<Buffer>((resolve) => {
    doc.on("end", () => resolve(Buffer.concat(chunks)));
  });

  // Header
  doc.fontSize(18).font("Helvetica-Bold").text(meta.orgName, { align: "left" });
  doc.moveDown(0.15);
  doc.fontSize(9).font("Helvetica");
  for (const line of meta.orgLines ?? []) doc.text(line);
  doc.moveDown(1);

  doc.fontSize(14).font("Helvetica-Bold").text(meta.title);
  if (meta.subtitle) {
    doc.fontSize(10).font("Helvetica").fillColor("#555555").text(meta.subtitle);
    doc.fillColor("#000000");
  }
  doc.moveDown(0.75);

  let y = doc.y;
  for (const block of blocks) {
    if (block.kind === "spacer") {
      doc.moveDown((block.height ?? 1) * 0.5);
      continue;
    }
    if (block.kind === "text") {
      doc.fontSize(9).font("Helvetica").text(block.text);
      doc.moveDown(0.5);
      continue;
    }
    if (block.kind === "keyValue") {
      doc.font("Helvetica");
      for (const [label, value] of block.rows) {
        doc.fontSize(9).fillColor("#555555").text(label, MARGIN, doc.y, { continued: false });
        doc.fillColor("#000000").font("Helvetica-Bold").text(value, MARGIN + 150, doc.y - doc.heightOfString(label));
        doc.moveDown(0.25);
      }
      doc.moveDown(0.5);
      continue;
    }
    if (block.kind === "table") {
      const { columns, rows, footer } = block.table;
      const startX = MARGIN;
      y = doc.y;

      // header row
      doc.font("Helvetica-Bold").fontSize(8.5);
      columns.forEach((col, i) => {
        const x = startX + columns.slice(0, i).reduce((acc, c) => acc + c.width, 0);
        doc.text(col.header, x, y, { width: col.width, align: col.align ?? "left" });
      });
      y += 16;
      doc.moveTo(startX, y).lineTo(startX + CONTENT_WIDTH, y).strokeColor("#999999").lineWidth(0.5).stroke();

      // body rows
      doc.font("Helvetica");
      for (const row of rows) {
        const rowY = y + 6;
        columns.forEach((col, i) => {
          const x = startX + columns.slice(0, i).reduce((acc, c) => acc + c.width, 0);
          doc.fontSize(8.5).text(String(row[i] ?? ""), x, rowY, { width: col.width, align: col.align ?? "left" });
        });
        const rowHeight = Math.max(
          ...columns.map((col, i) =>
            doc.heightOfString(String(row[i] ?? ""), { width: col.width }),
          ),
        );
        y = rowY + rowHeight + 6;
        doc
          .moveTo(startX, y)
          .lineTo(startX + CONTENT_WIDTH, y)
          .strokeColor("#DDDDDD")
          .lineWidth(0.5)
          .stroke();
      }

      if (footer) {
        y += 10;
        for (const f of footer) {
          doc.font("Helvetica-Bold").fontSize(9).text(f.label, startX, y);
          doc.text(f.value, startX + CONTENT_WIDTH - 120, y, { width: 120, align: "right" });
          y += 16;
        }
      }
      doc.y = y + 12;
    }
  }

  doc.moveDown(1.5);
  doc
    .fontSize(7.5)
    .fillColor("#777777")
    .text(
      "This document was generated by the Bhumi Landmarks management system. Historical documents are preserved as issued.",
      MARGIN,
      doc.page.height - MARGIN - 30,
      { width: CONTENT_WIDTH, align: "center", lineBreak: false },
    );

  doc.end();
  return done;
}
